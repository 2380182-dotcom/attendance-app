-- "Salesman updates" feature, part 2: a salesman reached a shop but
-- couldn't make a sale, so he records feedback instead of a voucher. New
-- table only — no existing table touched, zero risk to existing data.
CREATE TABLE shop_feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    agent_id BIGINT NOT NULL,
    customer_shop_id BIGINT NOT NULL REFERENCES customer_shops(id),
    reason VARCHAR(30) NOT NULL,
    note TEXT,
    gps_latitude DOUBLE PRECISION NOT NULL,
    gps_longitude DOUBLE PRECISION NOT NULL,
    distance_from_shop_meters DOUBLE PRECISION,
    geofence_status VARCHAR(20) NOT NULL,
    visit_date DATE NOT NULL,
    visit_time TIME NOT NULL,
    request_id VARCHAR(64),
    created_at TIMESTAMP
);

-- Race-proof idempotency guard, same pattern as ux_sales_records_request_id
-- (V27) — nullable, and a UNIQUE index treats every NULL as distinct from
-- every other NULL, so old app builds that never send one are unaffected.
CREATE UNIQUE INDEX ux_shop_feedback_request_id ON shop_feedback(request_id);

-- The admin "QR Scanned Shops" report's per-day lookups.
CREATE INDEX ix_shop_feedback_agent_date ON shop_feedback (agent_id, visit_date);
CREATE INDEX ix_shop_feedback_shop_date ON shop_feedback (customer_shop_id, visit_date);
