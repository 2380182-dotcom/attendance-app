-- Company holidays (per tenant), managed by Admin on the web dashboard.
-- The 10 PM absence job skips these dates. One holiday per date per company.
CREATE TABLE company_holiday (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    holiday_date DATE NOT NULL,
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT ux_company_holiday_date UNIQUE (tenant_id, holiday_date)
);
