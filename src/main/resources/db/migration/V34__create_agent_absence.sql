-- One row per mart agent (role AGENT) per working day with no check-in,
-- saved by the 10 PM job. The unique key makes a duplicate impossible even
-- if the job runs twice or on two instances at once. Deliberately a
-- separate table, not an attendance row: an "absent" attendance row would
-- look like an open shift and block that agent's next real check-in.
-- agent_id has no foreign key (same as shop_feedback); deleting an agent
-- removes their absences in AgentService.deleteAgent.
CREATE TABLE agent_absence (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    agent_id BIGINT NOT NULL,
    absence_date DATE NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT ux_agent_absence_agent_date UNIQUE (tenant_id, agent_id, absence_date)
);
CREATE INDEX ix_agent_absence_tenant_date ON agent_absence (tenant_id, absence_date);
