-- Product families and order from Dawn Bread's official list
-- (26-10-2026 Dawn List.pdf). Every product list (app, dashboard, reports)
-- shows products in the list's SR No. order; the app's family filter
-- buttons come from product_families. Admin can change both later on the
-- Pricing page, so a new list needs no code change.
--
-- Names, prices, categories and On/Hidden of existing products are NOT
-- changed. Two products on the list that the system did not have yet
-- (SR 53 Crumbs 500 GM, SR 54 Crumbs 1000 GM) are added HIDDEN with prices
-- "Not set", like V38's.

CREATE TABLE product_families (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   BIGINT       NOT NULL REFERENCES tenants(id),
    name        VARCHAR(40)  NOT NULL,
    -- Urdu label for the app's filter buttons; NULL = English only.
    name_ur     VARCHAR(60),
    sort_order  INT          NOT NULL,
    created_at  TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMP,
    CONSTRAINT ux_product_families_tenant_name UNIQUE (tenant_id, name)
);

-- family_id NULL = no family yet (shown last, under "Other").
-- sort_order: the list's SR No.; products not on the list come after it.
-- NULL = not placed yet (after every placed product, by id).
-- on_price_list: true = on the official list; the app's "All" view shows
-- the others in their own last group.
ALTER TABLE products ADD COLUMN family_id BIGINT REFERENCES product_families(id);
ALTER TABLE products ADD COLUMN sort_order INT;
ALTER TABLE products ADD COLUMN on_price_list BOOLEAN NOT NULL DEFAULT false;
CREATE INDEX ix_products_family_id ON products (family_id);

-- The filter buttons, in the list's order (Cake split out of the list's
-- Sweets family, as Dawn Bread asked). DAWNBREAD only.
INSERT INTO product_families (tenant_id, name, sort_order, created_at)
SELECT t.id, v.name, v.sort_order, NOW()
FROM tenants t
CROSS JOIN (VALUES ('Bread', 1), ('Pitta', 2), ('Burger', 3), ('Bun', 4),
                   ('Cake', 5), ('Sweets', 6), ('Rusk', 7), ('Frozen', 8)) AS v(name, sort_order)
WHERE t.company_code = 'DAWNBREAD';

-- SR 53 and 54: same category and unit as the existing Crumbs; skipped if
-- the name already exists for the company.
INSERT INTO products (tenant_id, name, category, unit, agent_price, salesman_price, is_active, created_at, updated_at)
SELECT t.id, v.name, 'OTHER', 'pack', NULL, NULL, false, NOW(), NOW()
FROM tenants t
CROSS JOIN (VALUES ('Crumbs 500 GM'), ('Crumbs 1000 GM')) AS v(name)
WHERE t.company_code = 'DAWNBREAD'
  AND NOT EXISTS (SELECT 1 FROM products p WHERE p.tenant_id = t.id AND lower(p.name) = lower(v.name));

